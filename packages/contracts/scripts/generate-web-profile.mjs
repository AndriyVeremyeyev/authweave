import { readFile, writeFile, mkdir } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

// Ship a dependency-free validator so the web app can be built in isolation.
const schema = JSON.parse(await readFile(new URL("../schemas/application-identity-profile.v1.schema.json", import.meta.url), "utf8"));
const fixture = JSON.parse(await readFile(new URL("../tests/fixtures/assessment-response.valid.json", import.meta.url), "utf8"));
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true, lines: true } });
const validate = ajv.compile(schema);
if (!validate(fixture.profile)) throw new Error("The preview example does not match the profile contract.");
const code = standaloneCode(ajv, validate);
if (code.includes("require(")) throw new Error("The generated validator needs a runtime dependency; review browser compatibility.");
const files = {
  "validate-profile.mjs": "// Generated by packages/contracts/scripts/generate-web-profile.mjs. Do not edit.\n" + code,
  "profile-schema.json": JSON.stringify(schema, null, 2) + "\n",
  "example-profile.json": JSON.stringify(fixture.profile, null, 2) + "\n",
};
const directory = new URL("../../../apps/web/src/lib/preview/generated/", import.meta.url);
const check = process.argv.includes("--check");
if (!check) await mkdir(directory, { recursive: true });
for (const [name, expected] of Object.entries(files)) {
  const destination = new URL(name, directory);
  if (check) {
    const actual = await readFile(destination, "utf8").catch(() => "");
    if (actual !== expected) throw new Error(`${name} is stale. Run node packages/contracts/scripts/generate-web-profile.mjs and commit the result.`);
  } else {
    await writeFile(destination, expected);
  }
}
console.log(check ? "Web profile contract artifacts are current." : "Generated web profile contract artifacts.");
